import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import { formatCurrencyForPdf } from "@/utils/exportPdf";
import { PAYMENT_METHOD_LABELS } from "@/utils/paymentMethod";
import type { BranchReport } from "@/lib/api/branchReport";

const BRAND: [number, number, number] = [15, 118, 110];
const INK: [number, number, number] = [30, 41, 59];
const MUTED: [number, number, number] = [71, 85, 105];

function titleCase(value: string): string {
  const spaced = value.replace(/_/g, " ");
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

function longDate(iso: string): string {
  const parsed = new Date(`${iso}T00:00:00`);
  return Number.isNaN(parsed.getTime())
    ? iso
    : parsed.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}

/**
 * What the report is called, which depends on the range it covers.
 *
 * A one-day range is the day-end report a manager hands over; anything wider
 * is a period summary. Hardcoding "Daily Report" would print a lie the first
 * time somebody picked a month.
 */
export function reportTitle(dateFrom: string, dateTo: string): string {
  return dateFrom === dateTo
    ? `Daily Report — ${longDate(dateFrom)}`
    : `Branch Report — ${longDate(dateFrom)} to ${longDate(dateTo)}`;
}

/**
 * The day-end PDF: a summary an Admin can read in a minute, followed by the
 * receipts that let them check any line of it.
 *
 * Money is written through `formatCurrencyForPdf` throughout — jsPDF's
 * built-in fonts have no Taka glyph, so `formatCurrency`'s "৳" comes out
 * mangled (see utils/exportPdf.ts).
 */
export function exportBranchReportPdf({
  report,
  branchName,
  generatedBy,
}: {
  report: BranchReport;
  branchName: string;
  generatedBy: string;
}) {
  const doc = new jsPDF();
  const money = (value: string) => formatCurrencyForPdf(Number(value));
  const pageWidth = doc.internal.pageSize.getWidth();

  // --- letterhead --------------------------------------------------------
  doc.setFontSize(15);
  doc.setTextColor(...BRAND);
  doc.text("Speech Therapy Lab", 14, 16);

  doc.setFontSize(9);
  doc.setTextColor(...MUTED);
  doc.text("Perfect Therapeutic Medicine", 14, 21);

  doc.setFontSize(12);
  doc.setTextColor(...INK);
  doc.text(reportTitle(report.dateFrom, report.dateTo), 14, 30);

  doc.setFontSize(8);
  doc.setTextColor(...MUTED);
  doc.text(branchName, 14, 35);
  doc.text(
    `Generated by ${generatedBy} · ${new Date().toLocaleString("en-GB")}`,
    pageWidth - 14,
    35,
    { align: "right" },
  );

  const after = () =>
    (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 7;

  /** One captioned table. An empty section still prints, showing a dash —
   *  "nothing today" is information, and a missing block reads as a bug. */
  const section = (head: string[], body: (string | number)[][], startY: number) => {
    autoTable(doc, {
      startY,
      head: [head],
      body:
        body.length > 0
          ? body.map((row) => row.map(String))
          : [["—", ...head.slice(1).map(() => "")]],
      headStyles: { fillColor: BRAND, fontSize: 8 },
      styles: { fontSize: 8, cellPadding: 1.8 },
      margin: { left: 14, right: 14 },
    });
    return after();
  };

  const caption = (text: string, y: number) => {
    doc.setFontSize(9);
    doc.setTextColor(...INK);
    doc.text(text, 14, y);
    return y + 3;
  };

  // --- 1-4: the money ----------------------------------------------------
  let y = caption("Money", 44);
  y = section(
    ["", "Amount"],
    [
      ["Collected", money(report.grossCollected)],
      ["Refunded", `- ${money(report.refunded)}`],
      ["Expenses", `- ${money(report.expenses)}`],
      ["Net", money(report.netRevenue)],
      ["Outstanding due (as of today)", money(report.outstandingDue)],
    ],
    y,
  );

  y = caption("Collected by method", y);
  y = section(
    ["Method", "Amount"],
    report.byMethod.map((row) => [
      PAYMENT_METHOD_LABELS[row.method as keyof typeof PAYMENT_METHOD_LABELS] ?? row.method,
      money(row.amount),
    ]),
    y,
  );

  y = caption("Collected by service type", y);
  y = section(
    ["Type", "Amount"],
    report.byCategory.map((row) => [titleCase(row.category), money(row.amount)]),
    y,
  );

  y = caption(
    `Expenses — approved ${money(report.expensesApproved)}, pending ${money(report.expensesPending)}`,
    y,
  );
  y = section(
    ["Category", "Count", "Amount"],
    report.expensesByCategory.map((row) => [titleCase(row.category), row.count, money(row.amount)]),
    y,
  );

  // Adjustments explain why the takings are not the sum of the receipts.
  if (report.refunds.length > 0 || report.voids.length > 0) {
    y = caption("Adjustments", y);
    y = section(
      ["Kind", "Receipt", "Patient", "Amount"],
      [
        ...report.refunds.map((row) => [
          "Refund",
          row.receiptNumber,
          row.patientName,
          money(row.amount),
        ]),
        ...report.voids.map((row) => [
          "Void",
          row.receiptNumber,
          row.patientName,
          money(row.amount),
        ]),
      ],
      y,
    );
  }

  // --- 5-10: the rest of the day ----------------------------------------
  y = caption("Patients and services", y);
  y = section(
    ["", "Count"],
    [
      ["New patients registered", report.newPatients],
      ["Patients seen (paid)", report.patientsSeen],
      ["Attendance — present", report.attendance.present],
      ["Attendance — informed absence", report.attendance.informed],
      ["Attendance — absent", report.attendance.absent],
      ["New monthly enrolments", report.services.newMonthly],
      ["New installment plans", report.services.newInstallmentPlans],
      ["Appointments booked", report.services.bookings],
      ["Appointments cancelled", report.services.bookingsCancelled],
    ],
    y,
  );

  if (report.materialsSold.length > 0) {
    y = caption("Materials sold", y);
    y = section(
      ["Item", "Qty", "Amount"],
      report.materialsSold.map((row) => [row.name, row.quantity, money(row.amount)]),
      y,
    );
  }

  y = caption("Staff attendance", y);
  y = section(
    ["Present", "Early leave", "On leave", "Absent"],
    [
      [
        report.staffAttendance.present,
        report.staffAttendance.early_leave,
        report.staffAttendance.on_leave,
        report.staffAttendance.absent,
      ],
    ],
    y,
  );

  y = caption(
    `Enquiries — ${report.enquiries.total} received, ${report.enquiries.converted} enrolled`,
    y,
  );
  y = section(
    ["Source", "Calls"],
    report.enquiries.bySource.map((row) => [titleCase(row.source), row.count]),
    y,
  );

  // --- 11: every receipt -------------------------------------------------
  doc.addPage();
  caption(`Receipts (${report.payments.length})`, 16);
  autoTable(doc, {
    startY: 20,
    head: [["Receipt", "Time", "Patient", "Type", "Method", "Collected by", "Amount"]],
    body: report.payments.map((row) => [
      row.receiptNumber,
      new Date(row.createdAt).toLocaleTimeString("en-GB", {
        hour: "2-digit",
        minute: "2-digit",
      }),
      `${row.patientName} (${row.patientCode})`,
      titleCase(row.category || "—"),
      PAYMENT_METHOD_LABELS[row.method as keyof typeof PAYMENT_METHOD_LABELS] ?? row.method,
      row.collectedBy || "—",
      money(row.amount),
    ]),
    foot: [["", "", "", "", "", "Total", money(report.grossCollected)]],
    headStyles: { fillColor: BRAND, fontSize: 8 },
    footStyles: { fillColor: [241, 245, 249], textColor: INK, fontStyle: "bold", fontSize: 8 },
    styles: { fontSize: 8, cellPadding: 1.8 },
    margin: { left: 14, right: 14 },
  });

  // Page numbers last, once the page count is known.
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text(
      `Page ${page} of ${pages}`,
      pageWidth - 14,
      doc.internal.pageSize.getHeight() - 8,
      { align: "right" },
    );
  }

  const stamp =
    report.dateFrom === report.dateTo ? report.dateFrom : `${report.dateFrom}_${report.dateTo}`;
  doc.save(`${branchName.replace(/\s+/g, "-")}-report-${stamp}.pdf`);
}
